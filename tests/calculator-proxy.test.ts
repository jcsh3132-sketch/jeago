import { after, test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { NextRequest } from 'next/server';
import { GET, POST } from '../src/app/calculator/content/[asset]/route';
import { register, createSession, SESSION_COOKIE } from '../src/lib/auth';
import { getDb } from '../src/lib/db';
mkdirSync('work', { recursive: true });
process.env.JEAGO_TEST_MODE = '1';
process.env.JEAGO_TEST_DATABASE_URL = pathToFileURL(join(mkdtempSync(join(resolve('work'),'proxy-test-')),'test.db')).href;
process.env.CALCULATOR_BASE_URL = 'https://calculator-test.invalid';
process.env.CALCULATOR_API_KEY = 'test-private-upstream-key';
after(async () => (await getDb()).close());
test('calculator proxy authenticates, isolates credentials, forwards updates/errors and protects writes', async t => {
  const user = await register({ username:'proxy.member',display_name:'테스트',password:'1234',password_confirm:'1234' });
  const token = await createSession(user.id,true);
  let revision = 1, called = 0, shouldFail = false;
  t.mock.method(globalThis,'fetch',async (url: URL, init: RequestInit) => {
    called++;
    assert.equal(url.origin,'https://calculator-test.invalid');
    assert.equal(new Headers(init.headers).get('X-Calculator-Key'),'test-private-upstream-key');
    assert.equal(new Headers(init.headers).get('Cookie'),null);
    assert.equal(init.cache,'no-store'); assert.equal(init.redirect,'error');
    if (shouldFail) throw new Error('test-private-upstream-key network failure');
    if (url.pathname === '/') return new Response('<html><head><link href="style.css?v=2"></head><body><button id="calcBtn"></button><script src="script.js?v=2"></script></body></html>',{headers:{'Content-Type':'text/html'}});
    if (url.pathname === '/api/cost-discounts') { assert.equal(init.method,'POST'); assert.equal(init.body,'{"model":"test","percent":100,"amount":0}'); return new Response('{"detail":"값 범위 오류"}',{status:422,headers:{'Content-Type':'application/json'}}); }
    return new Response(JSON.stringify({ revision, extra:'unmodified upstream field' }),{headers:{'Content-Type':'application/json'}});
  });
  const context = (asset: string) => ({ params: Promise.resolve({ asset }) });
  const request = (body?: string, origin = 'https://jeago.test') => new NextRequest('https://jeago.test/calculator/content/index',{method:body===undefined?'GET':'POST',headers:{Host:'jeago.test',Cookie:`${SESSION_COOKIE}=${token}`,Origin:origin,'Content-Type':'application/json'},...(body===undefined?{}:{body})});
  for (const asset of ['index','script','style.css','sale-products','rent-products','api-settings']) assert.equal((await GET(new NextRequest('https://jeago.test'),context(asset))).status,401);
  assert.equal((await POST(new NextRequest('https://jeago.test',{method:'POST'}),context('cost-discounts'))).status,401);
  assert.equal(called,0);
  const htmlResponse=await GET(request(),context('index')), html=await htmlResponse.text();
  assert(html.includes('/calculator/content/style.css?v=2')); assert(html.includes('/calculator/content/script.js?v=2'));
  assert(html.indexOf('window.CALCULATOR_API')<html.indexOf('src="/calculator/content/script.js'));
  assert(html.includes(encodeURIComponent(user.id))); assert(!html.includes('test-private-upstream-key'));
  assert.equal(htmlResponse.headers.get('cache-control'),'private, no-store');
  assert.equal(htmlResponse.headers.get('set-cookie'),null);
  assert.equal((await GET(request(),context('sale-products'))).headers.get('content-type'),'application/json');
  revision=2; assert.equal((await (await GET(request(),context('sale-products'))).json()).revision,2);
  const before=called;
  assert.equal((await GET(request(),context('__proto__'))).status,404);
  assert.equal((await POST(request('{}','https://evil.test'),context('cost-discounts'))).status,403);
  assert.equal((await POST(request('x'.repeat(4097)),context('cost-discounts'))).status,413);
  assert.equal(called,before);
  const bad=await POST(request('{"model":"test","percent":100,"amount":0}'),context('cost-discounts'));
  assert.equal(bad.status,422); assert.deepEqual(await bad.json(),{detail:'값 범위 오류'});
  shouldFail=true;
  const failure=await GET(request(),context('sale-products')); assert.equal(failure.status,502); assert(!(await failure.text()).includes('test-private-upstream-key'));
});
