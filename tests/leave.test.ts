test('leave calculation matches supplied workbook cached examples and date boundaries', () => {
  const examples = [['2024-06-03',1,34,33,-1],['2024-02-21',1,35,39,4],['2020-12-14',0,87,90,3],['2025-01-21',0,24.5,23,-1.5],['2025-01-02',0,22,23,1]] as const;
  for (const [hired,special,used,earned,remaining] of examples) { const result=calculateLeave(hired,'2026-08-25',special,used); assert.equal(result.earned,earned); assert.equal(result.remaining,remaining); }
  assert.equal(calculateLeave('2025-01-31','2025-02-28',0,0).months,0);
  assert.equal(calculateLeave('2024-02-29','2025-02-28',0,0).earned,11);
  assert.equal(calculateLeave('2024-02-29','2025-03-01',0,0).earned,15);
  assert.equal(calculateLeave('2020-01-01','2023-01-01',0,0).earned,46);
  assert.throws(() => calculateLeave('2025-02-30','2026-01-01',0,0));
  assert.throws(() => calculateLeave('2025-02-01','2025-01-01',0,0));
  assert.equal(weekdays('2026-09-18','2026-09-21'),2);
});
test('leave ownership prevents cross-account reads, edits and impersonation', async () => {
  const a=await register({username:'leave.a',display_name:'A',password:'1234',password_confirm:'1234'});
  const b=await register({username:'leave.b',display_name:'B',password:'1234',password_confirm:'1234'});
  const token=await createSession(a.id,true), other=await createSession(b.id,true);
  const employee={id:randomUUID(),name:'테스트',position:'사원',hired:'2025-01-01',special:1,version:0,entries:[{id:randomUUID(),start:'2026-01-02',end:'2026-01-02',days:0.5,note:''}]};
  const request={employee,request_id:randomUUID()};
  await assert.rejects(saveLeave(undefined,request)); await assert.rejects(leaveEmployees(undefined));
  await saveLeave(token,request); await saveLeave(token,request);
  assert.equal((await leaveEmployees(token))[0].version,1);
  assert.deepEqual(await leaveEmployees(other),[]);
  await assert.rejects(saveLeave(other,{...request,request_id:randomUUID()}),/본인/);
  await assert.rejects(saveLeave(token,{...request,request_id:randomUUID()}),/다른 회원/);
  await saveLeave(token,{employee:{...employee,name:'수정',version:1},request_id:randomUUID()});
  assert.equal((await leaveEmployees(token))[0].name,'A');
  await assert.rejects(saveLeave(token,{employee:{...employee,id:randomUUID()},request_id:randomUUID()}),/이미 본인/);
  const unlinked={...employee,id:randomUUID()};
  await (await getDb()).execute({sql:'INSERT INTO leave_employee(id,name,position,hired,special,entries) VALUES (?,?,?,?,?,?)',args:[unlinked.id,'B','사원','2025-01-01',0,'[]']});
  await assert.rejects(saveLeave(other,{employee:unlinked,request_id:randomUUID()}),/본인/);
  await (await getDb()).execute({sql:'INSERT INTO app_admin(singleton,user_id) VALUES(1,?)',args:[b.id]});
  await saveLeave(other,{employee:{...employee,version:2},request_id:randomUUID()});
  await assert.rejects(saveLeave(token,{employee:{...employee,version:2,entries:[{...employee.entries[0],days:-1}]},request_id:randomUUID()}));
  const own = (await leaveEmployees(token))[0];
  await assert.rejects(saveLeave(token,{employee:{...own,entries:[]},request_id:randomUUID()}),/삭제할 수 없습니다/);
  await assert.rejects(saveLeave(token,{employee:{...own,entries:[{...own.entries[0],days:1}]},request_id:randomUUID()}),/관리자만/);
  const appended = {...own,entries:[...own.entries,{...own.entries[0],id:randomUUID(),start:'2026-01-03',end:'2026-01-03'}]};
  await saveLeave(token,{employee:appended,request_id:randomUUID()});
  await (await getDb()).execute({sql:'UPDATE app_admin SET user_id=? WHERE singleton=1',args:[a.id]});
  const adminOwn = (await leaveEmployees(token))[0];
  await saveLeave(token,{employee:{...adminOwn,entries:adminOwn.entries.map((entry,i)=>i===0?{...entry,days:1}:entry)},request_id:randomUUID()});
  const edited = (await leaveEmployees(token))[0];
  assert.equal(edited.entries[0].days,1);
  await assert.rejects(saveLeave(token,{employee:{...edited,entries:edited.entries.slice(1)},request_id:randomUUID()}),/삭제할 수 없습니다/);
  await (await getDb()).execute({sql:'UPDATE app_admin SET user_id=? WHERE singleton=1',args:[b.id]});
  await assert.rejects(saveLeave(token,{employee:{...edited,entries:edited.entries.map(e=>({...e,days:2}))},request_id:randomUUID()}),/관리자만/);
  await (await getDb()).execute({sql:'INSERT INTO leave_admin(user_id) VALUES (?)',args:[a.id]});
  assert.equal((await leaveEmployees(token)).length,2);
  await assert.rejects(listMembers(token), /관리자만/);
  const unrelated=(await leaveEmployees(token)).find(e=>e.id===unlinked.id)!;
  await saveLeave(token,{employee:{...unrelated,position:'수정 직급'},request_id:randomUUID()});
  assert.equal((await leaveEmployees(token)).find(e=>e.id===unlinked.id)!.name,'B');
  await saveLeave(token,{employee:{...unrelated,version:1,entries:employee.entries},request_id:randomUUID()});
  const managed = (await leaveEmployees(token)).find(e=>e.id===unlinked.id)!;
  assert.equal(managed.entries.length,1);
  await assert.rejects(saveLeave(token,{employee:{...managed,entries:[]},request_id:randomUUID()}),/삭제할 수 없습니다/);
  await assert.rejects(saveLeave(token,{employee:{...edited,entries:[]},request_id:randomUUID()}),/삭제할 수 없습니다/);
});

test('both leave administrators can register leave for another employee without changing ownership', async () => {
  const owner = await register({username:'managed.owner',display_name:'관리 대상 직원',password:'1234',password_confirm:'1234'});
  const ownerToken = await createSession(owner.id,true);
  const employee = {id:randomUUID(),name:owner.display_name,position:'사원',hired:'2024-01-01',special:0,version:0,entries:[]};
  await saveLeave(ownerToken,{employee,request_id:randomUUID()});
  for (const username of ['leave.manager.one','leave.manager.two']) {
    const manager = await register({username,display_name:username,password:'1234',password_confirm:'1234'});
    const token = await createSession(manager.id,true);
    const db = await getDb();
    await db.execute({sql:'INSERT INTO leave_admin(user_id) VALUES (?)',args:[manager.id]});
    const current = (await leaveEmployees(token)).find(e=>e.id===employee.id)!;
    const entry = {id:randomUUID(),start:'2026-09-30',end:'2026-09-30',days:0.5,note:username};
    const request = {employee:{...current,name:username,entries:[...current.entries,entry]},request_id:randomUUID()};
    await saveLeave(token,request);
    await saveLeave(token,request);
    const saved = (await leaveEmployees(ownerToken))[0];
    assert.equal(saved.name,owner.display_name);
    assert.equal(saved.is_self,true);
    assert.equal(saved.version,current.version+1);
    assert.equal(saved.entries.length,current.entries.length+1);
    const { approval, ...savedEntry } = saved.entries.at(-1)!;
    assert.deepEqual(savedEntry,entry);
    assert.equal(approval?.status,'pending_first');
    const audit = (await db.execute({sql:'SELECT updated_by,user_id FROM leave_employee WHERE id=?',args:[employee.id]})).rows[0];
    assert.equal(audit.updated_by,manager.id);
    assert.equal(audit.user_id,owner.id);
    await assert.rejects(saveLeave(token,{...request,request_id:randomUUID()}),/다른 회원/);
    await assert.rejects(saveLeave(token,{employee:{...saved,entries:[]},request_id:randomUUID()}),/삭제할 수 없습니다/);
    await assert.rejects(listMembers(token),/관리자만/);
    await db.execute({sql:'DELETE FROM leave_admin WHERE user_id=?',args:[manager.id]});
    await assert.rejects(saveLeave(token,{employee:{...saved,entries:[...saved.entries,{...entry,id:randomUUID()}]},request_id:randomUUID()}),/본인/);
  }
  const saved = (await leaveEmployees(ownerToken))[0];
  assert.equal(saved.entries.length,2);
  await assert.rejects(saveLeave(ownerToken,{employee:{...saved,entries:saved.entries.map(e=>({...e,days:1}))},request_id:randomUUID()}),/관리자만/);
});

test('leave deducts only after ordered approvals, preserves legacy and prevents forged or stale approval', async () => {
  const db = await getDb();
  const accounts = [];
  for (const name of ['approval.owner','approval.first','approval.final','approval.outsider']) {
    const user = await register({username:name,display_name:name,password:'1234',password_confirm:'1234'});
    accounts.push({...user,token:await createSession(user.id,true)});
  }
  const [owner, first, final, outsider] = accounts;
  await db.execute({sql:'INSERT INTO leave_admin(user_id,approval_stage) VALUES (?,1),(?,2)',args:[first.id,final.id]});
  const legacy = {id:randomUUID(),start:'2026-01-05',end:'2026-01-05',days:1,note:'기존 사용 내역'};
  const employeeId = randomUUID();
  await db.execute({sql:'INSERT INTO leave_employee(id,user_id,name,position,hired,entries,version) VALUES (?,?,?,?,?,?,1)',args:[employeeId,owner.id,owner.display_name,'사원','2024-01-01',JSON.stringify([legacy])]});
  const read = async () => (await leaveEmployees(owner.token))[0];
  let employee = await read();
  const newEntry = {id:randomUUID(),start:'2026-10-01',end:'2026-10-01',days:0.5,note:'새 신청',approval:{status:'approved',submitted_by:final.id,submitted_at:'2020-01-01',first:{user_id:first.id,username:first.username,at:'2020-01-01'},final:{user_id:final.id,username:final.username,at:'2020-01-01'}}};
  await saveLeave(owner.token,{employee:{...employee,entries:[...employee.entries,newEntry]},request_id:randomUUID()});
  employee = await read();
  assert.deepEqual(employee.entries[0],legacy);
  assert.equal(employee.entries[1].approval?.status,'pending_first');
  assert.equal(employee.entries[1].approval?.first,undefined);
  assert.equal(approvedLeaveDays(employee.entries),1);
  assert.equal(pendingLeaveDays(employee.entries),0.5);
  const approvalRequest = (stage: number, version=employee.version) => ({action:'approve',employee_id:employeeId,entry_id:newEntry.id,stage,version,request_id:randomUUID()});
  await assert.rejects(approveLeave(undefined,approvalRequest(1)),/로그인/);
  await assert.rejects(approveLeave(owner.token,approvalRequest(1)),/지정 승인자/);
  await assert.rejects(approveLeave(outsider.token,approvalRequest(1)),/지정 승인자/);
  const siteAdmin = String((await db.execute('SELECT user_id FROM app_admin WHERE singleton=1')).rows[0].user_id);
  await assert.rejects(approveLeave(await createSession(siteAdmin,true),approvalRequest(2)),/지정 승인자/);
  await assert.rejects(approveLeave(first.token,approvalRequest(2)),/지정 승인자/);
  await assert.rejects(approveLeave(final.token,approvalRequest(1)),/지정 승인자/);
  await assert.rejects(approveLeave(final.token,approvalRequest(2)),/1차 승인/);
  const firstRequest = approvalRequest(1);
  const approvals = await Promise.allSettled([approveLeave(first.token,firstRequest),approveLeave(first.token,{...firstRequest,request_id:randomUUID()})]);
  assert.equal(approvals.filter(r=>r.status==='fulfilled').length,1);
  // The winning request can be replayed without changing balances or incrementing the version twice.
  if (approvals[0].status === 'fulfilled') await approveLeave(first.token,firstRequest);
  employee = await read();
  assert.equal(employee.entries[1].approval?.status,'pending_final');
  assert.equal(employee.entries[1].approval?.first?.user_id,first.id);
  assert.equal(approvedLeaveDays(employee.entries),1);
  await assert.rejects(approveLeave(final.token,approvalRequest(2,firstRequest.version)),/내역이 변경/);
  const finalRequest = approvalRequest(2);
  await approveLeave(final.token,finalRequest);
  await approveLeave(final.token,finalRequest);
  employee = await read();
  assert.equal(employee.entries[1].approval?.status,'approved');
  assert.equal(employee.entries[1].approval?.final?.user_id,final.id);
  assert.equal(approvedLeaveDays(employee.entries),1.5);
  assert.equal(pendingLeaveDays(employee.entries),0);
  const confirmed = employee.entries[1].approval;
  // Ordinary saves cannot remove approval data or change legacy records.
  await saveLeave(owner.token,{employee:{...employee,entries:employee.entries.map(({approval,...entry})=>entry)},request_id:randomUUID()});
  employee = await read();
  assert.deepEqual(employee.entries[0],legacy);
  assert.deepEqual(employee.entries[1].approval,confirmed);
  await saveLeave(first.token,{employee:{...employee,entries:employee.entries.map(e=>e.id===newEntry.id?{...e,days:1}:e)},request_id:randomUUID()});
  employee = await read();
  assert.equal(employee.entries[1].approval?.status,'pending_first');
  assert.equal(employee.entries[1].approval?.first,undefined);
  assert.equal(employee.entries[1].approval?.final,undefined);
  assert.equal(approvedLeaveDays(employee.entries),1);
  await assert.rejects(approveLeave(final.token,approvalRequest(2)),/1차 승인/);
  await db.execute({sql:'UPDATE app_user SET username=? WHERE id=?',args:['approval.first.renamed',first.id]});
  await approveLeave(first.token,approvalRequest(1));
  employee = await read();
  await db.execute({sql:'DELETE FROM leave_admin WHERE user_id=?',args:[final.id]});
  await assert.rejects(approveLeave(final.token,approvalRequest(2)),/指定|지정 승인자/);
  assert.equal(approvedLeaveDays((await read()).entries),1);
});
